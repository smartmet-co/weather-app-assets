#!/usr/bin/env node
// Splits locations/locations.json into locations/locations-N.json chunks and
// generates locations/index.ts, which joins them at runtime.
//
// Why: Metro bundles each imported JSON file as a single array literal, and
// Hermes corrupts its heap when an array literal holds more than 65,535
// objects (element 65535 is lost and the GC later crashes in release builds).
// Keeping every chunk well below that limit avoids the bug.
//
// Safe to re-run: previous chunks are removed before writing new ones.

const fs = require('fs');
const path = require('path');

const CHUNK_SIZE = 50000;
const HERMES_ARRAY_LITERAL_LIMIT = 65535;

const LOCATIONS_DIR = path.join(__dirname, '../locations');
const LOCATIONS_PATH = path.join(LOCATIONS_DIR, 'locations.json');
const INDEX_PATH = path.join(LOCATIONS_DIR, 'index.ts');
const CHUNK_PATTERN = /^locations-\d+\.json$/;

if (CHUNK_SIZE >= HERMES_ARRAY_LITERAL_LIMIT) {
  throw new Error(`CHUNK_SIZE must be below ${HERMES_ARRAY_LITERAL_LIMIT}`);
}

const data = JSON.parse(fs.readFileSync(LOCATIONS_PATH, 'utf8'));
if (!Array.isArray(data) || data.length === 0) {
  throw new Error(`${LOCATIONS_PATH} must contain a non-empty array`);
}

fs.readdirSync(LOCATIONS_DIR)
  .filter((file) => CHUNK_PATTERN.test(file))
  .forEach((file) => fs.unlinkSync(path.join(LOCATIONS_DIR, file)));

const chunkNames = [];
for (let start = 0; start < data.length; start += CHUNK_SIZE) {
  const name = `locations-${chunkNames.length}`;
  const chunk = data.slice(start, start + CHUNK_SIZE);
  fs.writeFileSync(path.join(LOCATIONS_DIR, `${name}.json`), JSON.stringify(chunk));
  chunkNames.push(name);
}

const identifiers = chunkNames.map((_, index) => `locations${index}`);
const index = `// Generated by scripts/split_locations_json.js. Do not edit.
//
// locations.json is split into chunks because Hermes corrupts its heap when a
// single array literal holds more than ${HERMES_ARRAY_LITERAL_LIMIT} objects. The chunks are
// joined at runtime instead.
import type { Location } from './types';
${chunkNames.map((name, i) => `import ${identifiers[i]} from './${name}.json';`).join('\n')}

const locations: Location[] = ([] as Location[]).concat(
${identifiers.map((id) => `  ${id} as Location[]`).join(',\n')}
);

export default locations;
`;
fs.writeFileSync(INDEX_PATH, index);

// locations.json is only an intermediate file; importing it would bring back
// the oversized array literal.
fs.unlinkSync(LOCATIONS_PATH);

console.log(`entries: ${data.length}`);
console.log(`chunks: ${chunkNames.length} (max ${CHUNK_SIZE} entries each)`);
console.log(`wrote: ${chunkNames.map((name) => `${name}.json`).join(', ')}, index.ts`);
